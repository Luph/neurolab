def xirr(flows, dates, guess=0.15):
    d0 = dates[0]
    yrs = np.array([(d - d0).days / 365.0 for d in dates]); cf = np.array(flows)
    r = guess
    for _ in range(200):
        v = (cf / (1 + r) ** yrs).sum(); dv = (-yrs * cf / (1 + r) ** (yrs + 1)).sum()
        nr = r - v / dv
        if abs(nr - r) < 1e-12: r = nr; break
        r = nr
    return r

def xnpv(rate, flows, dates, d0=None):
    d0 = d0 or dates[0]
    return sum(c / (1 + rate) ** ((d - d0).days / 365.0) for c, d in zip(flows, dates))

