def run(p, prof=None, N_m=None, N_s=None, bond_prof=None, D_fixed=None, gearing=None):
    """Run one scenario. prof: contractual repayment profile (array NS, fractions summing to 1).
    N_m/N_s: swap notional (monthly / semiannual opening). bond_prof: bond % of face."""
    global G
    G_saved = G
    if gearing is not None: G = gearing
    ERRS.clear(); ERRS.update(p.get('errs', ()))
    try:
        return _run(p, prof, N_m, N_s, bond_prof, D_fixed)
    finally:
        G = G_saved

def _run(p, prof, N_m, N_s, bond_prof, D_fixed):
    R = {}
    mac_ = build_macro(p)
    u = construction_uses(p, mac_)
    if prof is None:
        prof = np.array(CONTRACT['prof_FC'] if p['profile'] == 'FC' else CONTRACT['prof_COD'])
    if N_m is None: N_m = np.array(CONTRACT['N_m'])
    if N_s is None: N_s = np.array(CONTRACT['N_s'])
    if bond_prof is None and p['refi']: bond_prof = np.array(CONTRACT['prof_BOND'])
    if p['constr'] == 'FC':
        mode = p.get('fund_mode') or ('regross' if (p['capex'] != 1.0 or p['cod_delay']) else 'contract')
        f = funding_fc(p, mac_, u, prof, N_m, N_s, D_fixed, mode)
    else:
        f = funding_act(p, mac_, u, prof, N_m, N_s)
    R['mac'] = mac_; R['u'] = u; R['f'] = f; R['prof'] = prof; R['N_m'] = N_m; R['N_s'] = N_s
    cod = u['cod']; expiry = add_months(cod, 300) - timedelta(days=1)
    t_cod, t1 = first_ds_period(p)
    fe = fund_end_month(p)
    S = {}   # semiannual rows
    def z(): return np.zeros(NS)
    # ---- timing
    om = z(); opdays = z(); oms = z(); ome = z()
    for t in range(NS):
        s_ = max(S_START[t], cod); e_ = min(S_END[t], expiry)
        if e_ >= s_:
            om[t] = months_between(s_, add_months(date(e_.year, e_.month, 1), 1))
            opdays[t] = (e_ - s_).days + 1
        oms[t] = min(max(months_between(cod, S_START[t]), 0), 300)
        ome[t] = oms[t] + om[t]
    last_op = max(t for t in range(NS) if om[t] > 0)
    S.update(om=om, opdays=opdays, oms=oms, ome=ome)
    flag_ds = np.array([1.0 if t >= t1 else 0.0 for t in range(NS)])
    # ---- plant
    av_prof = INP['plant']['availability_profile_pct_by_operating_year_cycle']['values']
    shock = p.get('avail_shock')       # Monte Carlo: availability shock by operating year (points)
    def av_oy(oy): return av_prof[(oy - 1) % 8] + (shock[oy - 1] if shock is not None and oy <= len(shock) else 0.0)
    A = z(); Ap = z(); yrs = z()
    for t in range(NS):
        if om[t] == 0: continue
        oya = int(oms[t] // 12) + 1
        ma = min(ome[t], oya * 12) - oms[t]; mb = om[t] - ma
        Ap[t] = (ma * av_oy(oya) + mb * av_oy(oya + 1)) / om[t]
        yrs[t] = (oms[t] + ome[t]) / 24
    A = np.where(om > 0, Ap + p['avail_d'], 0.0)
    act = p['constr'] == 'ACT'
    C = p.get('C_override') or (581.9 if act else 588.4)
    HRg = p.get('HR_override') or (6286 if act else 6261)
    OF = (1 - 0.0015 * yrs) * 0.99
    HRF = (1 + p.get('hr_nr', 0.12) / 100 * yrs) * 1.008
    # dispatch factor when available: scenario value; actual history uses the 2022 drought dispatch (annex 4.11)
    disp = np.full(NS, float(p['dispatch']))
    if p.get('disp_path'):
        for lab, v in ACT_DISPATCH.items(): disp[tix(lab)] = v
    E = C * 730 * om * A / 100 * disp / 100 * OF          # MWh
    HRa = HRg * HRF * 1.023 * p['hr_f']
    HRc = 6323 * (1 + 0.001 * yrs) * 1.023
    yrf = np.array(S_YEAR) - 2018
    pgas = 5.86 * 1.02 ** yrf * p['gas_f']
    gas = E * HRa * K_GAS                                           # MMBtu
    fuel_rev = E * HRc * K_GAS * pgas / 1e6 * ((76.5 / p['dispatch']) if 'E9' in ERRS else 1.0)
    fuel_cost = gas * pgas / 1e6
    top_vol = 0.8 * 72400 * opdays
    top_short = np.maximum(0, top_vol - gas)
    top_pay = top_short * pgas / 1e6
    esc = 1.015 ** yrf
    gta_res = 96500 * opdays * 0.62 * esc / 1e6
    gta_com = gas * 0.19 * esc / 1e6
    S.update(dispatch=disp, avail=A, avail_prof=Ap, yrs=yrs, out_factor=OF, energy=E, hr_act=HRa, hr_con=HRc,
             gas_price=pgas, gas_mmbtu=gas, fuel_rev=fuel_rev, fuel_cost=fuel_cost,
             top_vol=top_vol, top_short=top_short, top_pay=top_pay, gta_res=gta_res, gta_com=gta_com)
    # ---- tariff
    m_ = mac_; fx = m_['fx']
    usT, kcT = m_['us_tar'] / 100, m_['kc_tar'] / 100
    cap_chg = 14.36 * p['cap_charge_f'] * (0.8 + 0.2 * usT)
    fom_chg = 2.31 * (0.62 * usT + 0.38 * kcT * 462.35 / fx)
    cpr = cap_chg + fom_chg
    avf = (A / 90.0) if 'E1' in ERRS else np.minimum(1, A / 90.0)
    CP = C * 1000 * om * cpr * avf / 1e6
    vom_rate = 3.86 * (0.7 * usT + 0.3 * kcT * 462.35 / fx)
    VOM = E * vom_rate / 1e6
    nonfuel = CP + VOM
    rev = nonfuel + fuel_rev + gta_res + gta_com + top_pay
    S.update(cap_charge=cap_chg, fom_charge=fom_chg, cpr=cpr, avail_factor=avf, cap_pay=CP,
             vom_rate=vom_rate, vom=VOM, nonfuel_rev=nonfuel, revenue=rev,
             us_tar=m_['us_tar'], kc_tar=m_['kc_tar'], us_cf=m_['us_cf'], kc_cf=m_['kc_cf'],
             fx=fx, base=m_['base_s'])
    # ---- opex
    us_cf, kc_cf = m_['us_cf'], m_['kc_cf']
    fo = p['fo_f']; mf = om / 12
    om_fix = 7.92 * (0.65 * us_cf + 0.35 * kc_cf * 516.8 / fx) * mf * fo
    om_inc = 0.60 * np.clip((A - 92) / 3, -1, 1) * us_cf * mf * (om > 0)
    ltsa_fix = 2.64 * us_cf * mf * fo
    eoh = (1 if 'E2' in ERRS else 2) * (8059 * np.divide(A, Ap, out=np.zeros(NS), where=Ap > 0) * disp / 76.5 + 38 * 10) * mf
    ltsa_var = eoh * 486 * us_cf / 1e6
    step = np.array([1.18 if (p['ins_step'] and t >= tix('2022H2')) else 1.0 for t in range(NS)])
    insur = 4.37 * us_cf * mf * step * fo
    ga = 3.18 * (0.5 * us_cf + 0.5 * kc_cf * 516.8 / fx) * mf * fo
    land = 368.0 * kc_cf / fx * mf * fo
    comm = 0.0055 * nonfuel
    consum = 1.08 * (0.7 * us_cf + 0.3 * kc_cf * 516.8 / fx) * E / 1e6
    agency = 0.255 * mf
    prg = 0.0075 * 41.5 * mf
    vat_int_ops = np.array([sum(u['vat_int'][m] for m in range(NM) if M_PER[m] == t and m > fe)
                            for t in range(NS)])
    fxl = z()
    if p['crisis']:
        for k_, v in INP['events']['offtaker_crisis']['fx_conversion_losses_usd_m'].items():
            fxl[tix(k_)] = v
    # major maintenance outside LTSA: spend in period containing month 7 of OY k
    mm_2018 = z()
    for t in range(NS):
        if om[t] == 0: continue
        k = int((ome[t] - 7) // 12) + 1
        if k >= 1 and oms[t] < (k - 1) * 12 + 7 <= ome[t] and k <= 24:
            mm_2018[t] = 9.47 if k % 8 == 0 else (2.18 if k % 4 == 0 else 0.0)
    mm = mm_2018 * us_cf
    # handback reserve from OY20 (months 229..300)
    hb_m = np.maximum(0, np.minimum(ome, 300) - np.maximum(oms, 228))
    hb_contr = 1.85 * us_cf * hb_m / 12
    opex_fixed = om_fix + om_inc + ltsa_fix + ltsa_var + insur + ga + land + comm + consum + agency + prg
    pass_cost = fuel_cost + gta_res + gta_com + top_pay
    hb_works = np.where(np.arange(NS) == last_op, hb_contr.sum(), 0.0)
    opex = opex_fixed + pass_cost + vat_int_ops + fxl + mm + hb_works
    S.update(om_fixed=om_fix, om_incentive=om_inc, ltsa_fixed=ltsa_fix, eoh=eoh, ltsa_var=ltsa_var,
             insurance=insur, ga=ga, land=land, community_levy=comm, consumables=consum,
             agency=agency, prg_fee=prg, vat_int_ops=vat_int_ops, fx_loss=fxl, mm_spend=mm,
             mm_2018=mm_2018, opex_om=opex_fixed, pass_cost=pass_cost, opex=opex,
             hb_months=hb_m, hb_contr_req=hb_contr, hb_works=hb_works)
    # ---- crisis: overdue receivables, gas arrears, late payment interest
    over = z(); lpi_acc = z(); lpi_rec = z()
    crisis = INP['events']['offtaker_crisis']
    if p['crisis']:
        for k_, v in crisis['overdue_receivables_usd_m_period_end'].items():
            tt = [t for t in range(NS) if S_END[t] == date.fromisoformat(k_)][0]
            over[tt] = v
        settle = date(2024, 3, 21)
        for t in range(NS):
            prev = over[t - 1] if t else 0.0
            dd = max(0, min((S_END[t] - S_START[t]).days + 1, (settle - S_START[t]).days))
            lpi_acc[t] = (prev + over[t]) / 2 * (m_['base_s'][t] - (CAS if t >= 9 else 0) + 2.0) / 100 * dd / 360
        tot = lpi_acc.sum() * 0.6
        for lab, sh in (('2024H1', 3 / 15), ('2024H2', 6 / 15), ('2025H1', 6 / 15)):
            lpi_rec[tix(lab)] = tot * sh
    gas_arr = GAS_ARREARS_SHARE * over
    S.update(overdue=over, lpi_accrued=lpi_acc, lpi_received=lpi_rec, gas_arrears=gas_arr)
    ebitda = rev - opex + lpi_rec
    S['ebitda'] = ebitda
    # ---- working capital
    rdays = np.full(NS, 45.0)
    xdays = np.zeros(NS)     # extra days on SEKA's capacity and VOM payments (sensitivities)
    if p['delay_days'] or p['lag_days']:
        xdays[SHOCK_T0:SHOCK_T0 + 2] = p['delay_days'] + p['lag_days']
    od = np.where(opdays > 0, opdays, 1)
    fin = np.arange(NS) >= last_op
    ar = np.where(fin, 0, rev / od * rdays + nonfuel / od * xdays)
    pay_gas = np.where(fin, 0, (fuel_cost + top_pay) / od * 45)
    pay_gta = np.where(fin, 0, (gta_res + gta_com) / od * 30)
    pay_om = np.where(fin, 0, (om_fix + om_inc + ltsa_fix + ltsa_var) / od * 30)
    pay_oth = np.where(fin, 0, (insur + ga + land + comm + consum + agency + prg) / od * 30)
    nwc = ar + over - pay_gas - pay_gta - pay_om - pay_oth - gas_arr
    dnwc = nwc - np.concatenate([[0], nwc[:-1]])
    inv_rel = np.where(np.arange(NS) == last_op, 5.35 * p['capex'], 0.0)
    S.update(rec_days=rdays, extra_days=xdays, ar=ar, pay_gas=pay_gas, pay_gta=pay_gta, pay_om=pay_om, pay_oth=pay_oth,
             nwc=nwc, dnwc=dnwc, inv_release=inv_rel)
    # ---- MMRA
    mm_contr = np.array([mm[t + 1:t + 7].sum() / 6 for t in range(NS)])
    mm_bal = np.cumsum(mm_contr - mm)
    S.update(mm_contr=mm_contr, mmra_bal=mm_bal)
    # ---- capitalized cost (book and tax)
    ld_rec = f['ld_received'].sum() if 'ld_received' in f else 0.0
    perf_ld = OVR['performance_lds_usd_m']['total'] if p['ld_prep'] else 0.0
    capcost = (f['uses'][:fe + 1].sum() - f['dsra'].sum() - u['wc'].sum() + f['shl_capint'].sum()
               - ld_rec - perf_ld)
    R['ld_rec'] = ld_rec; R['perf_ld'] = perf_ld
    R['capcost'] = capcost
    # ---------------- semiannual loop: debt, tax, waterfall, accounts ----------------------
    # balances at end of funding period
    nT = 6   # ECA, A, B, COM, SB, BOND
    names = TR + ['SB', 'BOND']
    bal0 = np.array([f['bal_' + k][fe] for k in TR] + [f['bal_SB'][fe], 0.0])
    B = np.zeros((nT, NS)); Bo = np.zeros((nT, NS)); P = np.zeros((nT, NS)); I = np.zeros((nT, NS))
    LDp = np.zeros((nT, NS)); RF = np.zeros((nT, NS)); SW = np.zeros((nT, NS)); DFo = np.zeros((nT, NS))
    DFc = np.zeros((nT, NS)); DFn = np.zeros((nT, NS)); DFr = np.zeros((nT, NS)); SCH = np.zeros((nT, NS))
    rows = {k: z() for k in [
        'swap', 'pri', 'pcg', 'waiver_fee', 'refi_costs', 'unwind', 'bond_face', 'interest_total',
        'principal_total', 'ds', 'senior_costs', 'tax', 'cit', 'mtt', 'taxable', 'ti_pre', 'pool_open',
        'pool_add', 'pool_use', 'pool_close', 'loss_use', 'loss_close', 'dep_full', 'dep_hol', 'dep_cur',
        'shl_int', 'shl_ded', 'thin_frac', 'int_ded', 'cfads', 'avail_cash', 'dsra_open', 'dsra_draw',
        'dsra_target', 'dsra_topup', 'dsra_release', 'dsra_close', 'shortfall', 'cash_after_ds',
        'hb_contr', 'hb_bal', 'hb_release', 'cash_dist', 'dist_ok', 'lockup', 'lu_count', 'lu_sweep',
        'mp_sweep', 'lu_close', 'shl_int_paid', 'shl_prin', 'div', 'trap_close', 'shl_open', 'shl_close',
        'ni', 're', 'book_dep', 'int_exp', 'dt', 'dt_exp', 'tax_exp', 'dscr', 'dscr_hist', 'eod',
        'released', 'comp_acct', 'rate_k_dummy', 'equity_dist', 'final_dist', 'lpi', 'int_cap',
        'ds_sched_next', 'book_nbv', 'tax_nbv', 'hold_rate', 'mtt_frac', 'nonhol_frac', 'cash_open',
        'ld_cash', 'sweep_lu_flag', 'sc_bal', 'cwip'
    ]}
    rr = rows
    # schedule helpers
    def rem(t): return prof[t:].sum()
    shl = f['shl_bal'][fe]; sc_bal = f['sc_contrib'].sum()
    pool = 0.0; loss = 0.0; dsra = 0.0; mmra = 0.0; hb = 0.0; lu = 0.0
    trap = 0.0; re_ = 0.0; comp = 0.0; prev_lock = 0; released = 0.0; dt_prev = 0.0
    taxcost = capcost
    # depreciation per month (full)
    dep_m_plant = 0.92 * taxcost / 240; dep_m_bld = 0.05 * taxcost / 300; dep_m_int = 0.03 * taxcost / 60
    bond_F = 0.0; deferred23 = np.zeros(nT); t23 = tix('2023H2')
    def mrg(t):
        v = np.array([MARGIN[0], MARGIN[1], MARGIN[2], com_margin(S_YEAR[t]), 0.0, 0.0])
        if p['waiver'] and tix('2023H2') <= t <= tix('2024H2'):
            v[:5] += 0.50
        return v
    def tranche_rate(t):   # fraction per period, for bank tranches 0..4 (SB blended), bond 5
        base = m_['base_s'][t]; dcf = S_DAYS[t] / 360; mg = mrg(t)
        r = np.zeros(nT)
        r[:4] = (base + mg[:4]) / 100 * (0.5 if 'E4' in ERRS else dcf) * GU
        up = 0.5 if (p['waiver'] and tix('2023H2') <= t <= tix('2024H2')) else 0.0
        r[4] = (0.6 * (base + com_margin(S_YEAR[t]) + 0.25 + up) / 0.9 + 0.4 * (base + 3.65 + 0.25 + up)) / 100 * dcf
        r[5] = 7.875 / 100 * 0.5
        return r
    swap_share = np.array([1.0 if not (p['refi'] and t > tix('2025H1')) else 0.52 for t in range(NS)])
    tR = tix('2025H1') if p['refi'] else -1
    for t in range(NS):
        # opening balances
        if t <= t_cod:
            Bo[:, t] = 0
        else:
            Bo[:, t] = B[:, t - 1]
        if t == t_cod:
            B[:, t] = bal0
        DFo[:, t] = DFc[:, t - 1] if t else 0
        r = tranche_rate(t)
        if t > t_cod:
            I[:, t] = Bo[:, t] * r
            # scheduled principal (pro rata to remaining contractual profile)
            if rem(t) > 1e-12:
                SCH[:5, t] = (Bo[:5, t] - DFo[:5, t]) * prof[t] / rem(t)
            if p['waiver'] and t == t23:
                DFn[:5, t] = 0.6 * SCH[:5, t]; deferred23 = DFn[:, t].copy()
            if p['waiver'] and tix('2024H1') <= t <= tix('2025H2'):
                DFr[:, t] = np.minimum(deferred23 / 4, DFo[:, t])
            P[:5, t] = SCH[:5, t] - DFn[:5, t] + DFr[:5, t]
            if Bo[5, t] > 0:
                P[5, t] = min(bond_F * bond_prof[t], Bo[5, t])
                SCH[5, t] = P[5, t]
            DFc[:, t] = DFo[:, t] + DFn[:, t] - DFr[:, t]
            rr['swap'][t] = N_s[t] * swap_share[t] * (SWAP_FIX / 100 * 0.5 - m_['base_s'][t] / 100 * S_DAYS[t] / 360) * (-1 if 'E10' in ERRS else 1)
            rr['pri'][t] = PRI * Bo[3, t] * S_DAYS[t] / 365
            rr['pcg'][t] = 0.011 * 0.5 * Bo[5, t] * (95.0 / bond_F if bond_F else 0)
            if p['waiver'] and t == t23:
                rr['waiver_fee'][t] = 0.0025 * Bo[:5, t].sum()
            # LD prepayment June 2022
            if p['ld_prep'] and t == tix('2022H1'):
                after = Bo[:5, t] - P[:5, t]
                LDp[:5, t] = OVR['performance_lds_usd_m']['total'] * after / after.sum()
            # refinancing June 2025
            if t == tR:
                RF[[2, 3, 4], t] = Bo[[2, 3, 4], t] - P[[2, 3, 4], t] - LDp[[2, 3, 4], t]
                DFc[[2, 3, 4], t] = 0
                prepaid = RF[:, t].sum()
                # swap unwind: 48% of notional, flat 3.68%
                mtm = 0.0
                for s in range(t + 1, NS):
                    mtm += 0.48 * N_s[s] * (3.68 - SWAP_FIX) / 100 * 0.5 / (1 + 0.0368 / 2) ** (s - t)
                rr['unwind'][t] = mtm
                bond_F = (prepaid + 3.10 + 0.0075 * 95.0 - mtm) / (0.99512 - 0.01)
                rr['bond_face'][t] = bond_F
                rr['refi_costs'][t] = bond_F * (1 - 0.99512) + 0.01 * bond_F + 3.10 + 0.0075 * 95.0
        rr['int_cap'][t] = 0.0
        rr['interest_total'][t] = I[:, t].sum()
        rr['principal_total'][t] = P[:, t].sum()
        rr['senior_costs'][t] = I[:, t].sum() + rr['swap'][t] + rr['pri'][t] + rr['pcg'][t]
        rr['ds'][t] = rr['senior_costs'][t] + P[:, t].sum()
        # ---------------- tax
        HE = 96 if 'E5' in ERRS else 60
        hol = max(0, min(ome[t], HE) - min(oms[t], HE))
        red = max(0, min(ome[t], 96) - min(max(oms[t], HE), 96))
        full = om[t] - hol - red
        dep_full = (dep_m_plant * max(0, min(ome[t], 240) - min(oms[t], 240))
                    + dep_m_bld * max(0, min(ome[t], 300) - min(oms[t], 300))
                    + dep_m_int * max(0, min(ome[t], 60) - min(oms[t], 60)))
        dep_hol = (dep_m_plant + dep_m_bld) * hol + dep_m_int * max(0, min(ome[t], min(60, HE)) - min(oms[t], min(60, HE)))
        dep_cur = dep_full - dep_hol
        rr['shl_open'][t] = shl if t >= t_cod else 0.0
        shl_int = shl * SHL_RATE / 100 * opdays[t] / 365 if t >= t_cod else 0.0
        if t == t_cod:  # interest accrues from COD
            shl_int = shl * SHL_RATE / 100 * opdays[t] / 365
        thin = min(1.0, 3 * (sc_bal + max(0.0, re_)) / shl) if (shl > 0 and t >= t_cod) else 1.0
        if p.get('no_thin'): thin = 1.0
        shl_ded = shl_int * thin
        int_ded = rr['senior_costs'][t] + rr['waiver_fee'][t] + rr['refi_costs'][t] - rr['unwind'][t]
        nh = (om[t] - hol) / om[t] if om[t] > 0 else 0.0
        ti_pre = (ebitda[t] - int_ded - shl_ded) * nh - dep_cur
        luse = min(loss, max(0.0, ti_pre)); ti2 = ti_pre - luse
        puse = min(pool, max(0.0, ti2)); ti3 = ti2 - puse
        lnew = max(0.0, -ti_pre)
        taxable = max(0.0, ti3)
        hr = (red * 15 + full * 30) / (red + full) / 100 if (red + full) > 0 else 0.0
        cit = taxable * hr
        mtt = 0.005 * nonfuel[t] * ((red + full) / om[t] if om[t] > 0 else 0.0) * (0.0 if p.get('no_mtt') else 1.0)
        tax = max(cit, mtt)
        rr['pool_open'][t] = pool
        pool = pool + (0.0 if 'E6' in ERRS else dep_hol) - puse; loss = loss - luse + lnew
        rr.update()
        for k_, v in (('dep_full', dep_full), ('dep_hol', dep_hol), ('dep_cur', dep_cur), ('shl_int', shl_int),
                      ('thin_frac', thin), ('shl_ded', shl_ded), ('int_ded', int_ded), ('ti_pre', ti_pre),
                      ('loss_use', luse), ('pool_use', puse), ('pool_add', dep_hol), ('pool_close', pool),
                      ('loss_close', loss), ('taxable', taxable), ('hold_rate', hr), ('cit', cit), ('mtt', mtt),
                      ('tax', tax), ('nonhol_frac', nh), ('mtt_frac', (red + full) / om[t] if om[t] > 0 else 0)):
            rr[k_][t] = v
        # ---------------- CFADS
        cfads = ebitda[t] - tax - dnwc[t] - mm_contr[t] + mm[t] + inv_rel[t]
        rr['cfads'][t] = cfads
        # ---------------- waterfall
        if p['ld_prep'] and t == t_cod:
            comp = OVR['performance_lds_usd_m']['total']
        ld_cash = 0.0
        if p['ld_prep'] and t == tix('2022H1'):
            ld_cash = comp; comp = 0.0
        rr['comp_acct'][t] = comp; rr['ld_cash'][t] = ld_cash
        if t == t_cod:
            dsra = f['dsra'].sum(); lu = f['ld_leftover']
        cash_open = lu + trap
        rr['cash_open'][t] = cash_open
        avail = cfads + cash_open
        rr['avail_cash'][t] = avail
        need = rr['senior_costs'][t] + rr['waiver_fee'][t] + P[:, t].sum()
        short = max(0.0, need - avail)
        dr = min(dsra, short)
        rr['dsra_open'][t] = dsra; rr['dsra_draw'][t] = dr; rr['shortfall'][t] = short - dr
        cad = max(0.0, avail - need)
        # DSRA target: next-period scheduled debt service on balances after this period's
        # scheduled payments and non-cash-dependent prepayments (LDs, refinancing)
        Bn = Bo[:, t] - P[:, t] - LDp[:, t] - RF[:, t] if t > t_cod else B[:, t].copy()
        if t == tR: Bn[5] = bond_F
        tgt = 0.0
        if t + 1 < NS and t >= t_cod:
            r1 = tranche_rate(t + 1)
            DFn_next = DFc[:, t]
            for k in range(5):
                if Bn[k] > 1e-9:
                    sched = (Bn[k] - DFn_next[k]) * prof[t + 1] / rem(t + 1) if rem(t + 1) > 1e-12 else 0.0
                    drep = min(deferred23[k] / 4, DFn_next[k]) if (p['waiver'] and tix('2024H1') <= t + 1 <= tix('2025H2')) else 0.0
                    tgt += sched + drep + Bn[k] * r1[k]
            if Bn[5] > 1e-9:
                tgt += min(bond_F * bond_prof[t + 1], Bn[5]) + Bn[5] * r1[5] + 0.011 * 0.5 * Bn[5] * 95.0 / bond_F
            tgt += N_s[t + 1] * swap_share[t + 1] * (SWAP_FIX / 100 * 0.5 - m_['base_s'][t + 1] / 100 * S_DAYS[t + 1] / 360) * (-1 if 'E10' in ERRS else 1)
            tgt += PRI * Bn[3] * S_DAYS[t + 1] / 365
        rr['dsra_target'][t] = tgt
        dsra_after = dsra - dr
        top = min(cad, max(0.0, tgt - dsra_after))
        rel = max(0.0, dsra_after - tgt)
        dsra = dsra_after + top - rel
        rr['dsra_topup'][t] = top; rr['dsra_release'][t] = rel; rr['dsra_close'][t] = dsra
        cash = cad - top + rel
        rr['cash_after_ds'][t] = cad
        # handback reserve
        hbc = min(cash, hb_contr[t]); hb += hbc
        hbr = hb if t == last_op else 0.0
        hb -= hbr
        cash = cash - hbc + hbr
        rr['hb_contr'][t] = hbc; rr['hb_bal'][t] = hb; rr['hb_release'][t] = hbr
        # distribution test (historic DSCR, 12 months)
        dsr = cfads / rr['ds'][t] if rr['ds'][t] > 1e-9 else 0.0
        rr['dscr'][t] = dsr
        if t >= 1 and rr['ds'][t - 1] > 1e-9:
            dh = (cfads + rr['cfads'][t - 1]) / (rr['ds'][t] + rr['ds'][t - 1])
        else:
            dh = dsr
        rr['dscr_hist'][t] = dh if rr['ds'][t] > 1e-9 else 0.0
        first_rep = rr['principal_total'][:t + 1].sum() > 1e-9
        eod = 1.0 if (rr['ds'][t] > 1e-9 and dh < 1.10) else 0.0
        waived = p['waiver'] and t in (tix('2023H1'), t23)
        rr['eod'][t] = eod
        in_waiver = p['waiver'] and t >= tix('2023H1')
        if in_waiver and t > t23:
            cond = (dh >= 1.25) and (rr['dscr_hist'][t - 1] >= 1.25 if t - 1 > t23 else False) \
                   and (dsra >= tgt - 1e-6)
            released = max(released, 1.0 if cond else 0.0)
        rr['released'][t] = released
        ok = first_rep and dh >= 1.20 and dsra >= tgt - 1e-6 and (eod == 0 or waived) \
            and rr['ds'][t] > 1e-9
        if in_waiver and not released:
            ok = False
        ok = ok or t == last_op and rr['ds'][t] <= 1e-9 or (rr['ds'][t] <= 1e-9 and t > t_cod and Bo[:, t].sum() < 1e-9)
        rr['dist_ok'][t] = 1.0 if ok else 0.0
        lock = (not ok) and first_rep and rr['ds'][t] > 1e-9
        cnt = (prev_lock + 1) if lock else 0
        prev_lock = cnt
        rr['lockup'][t] = 1.0 if lock else 0.0; rr['lu_count'][t] = cnt
        lusw = 0.0; mpsw = 0.0
        sweep_ok = cnt >= 2 and not in_waiver
        if not ok:
            if sweep_ok:
                lusw = min(cash, Bo[:5, t].sum() - P[:5, t].sum() - LDp[:5, t].sum() - RF[:5, t].sum())
                after = Bo[:5, t] - P[:5, t] - LDp[:5, t] - RF[:5, t]
                if after.sum() > 1e-9:
                    SW[:5, t] = lusw * after / after.sum()
            lu = cash - lusw; trap = 0.0
            dist = 0.0
        else:
            lu = 0.0
            if S_YEAR[t] >= 2027 and p['miniperm']:
                comm_after = Bo[3, t] - P[3, t] - LDp[3, t] - RF[3, t]
                mpsw = min(0.5 * cash, comm_after)
                SW[3, t] += mpsw
            dist = cash - mpsw
        rr['lu_sweep'][t] = lusw; rr['mp_sweep'][t] = mpsw; rr['lu_close'][t] = lu
        rr['cash_dist'][t] = dist
        # SHL and dividends
        due = shl_int
        sip = min(dist, due) if ok else 0.0
        shl = shl + shl_int - sip
        spr = min(dist - sip, shl) if ok else 0.0
        shl -= spr
        # accounting NI
        book_dep = capcost / 300 * om[t]
        int_exp = rr['senior_costs'][t] + rr['waiver_fee'][t] + rr['refi_costs'][t] - rr['unwind'][t] + shl_int
        tax_nbv = taxcost - sum(rr['dep_full'][:t + 1])
        book_nbv = capcost - sum(capcost / 300 * om[:t + 1])
        dtv = 0.30 * (book_nbv - (tax_nbv + pool)) if t >= t_cod else 0.0
        dt_exp = dtv - dt_prev; dt_prev = dtv
        ni = ebitda[t] - book_dep - int_exp - tax - dt_exp
        dcap = max(0.0, re_ + ni)
        dv = min(dist - sip - spr, dcap) if ok else 0.0
        trap = (dist - sip - spr - dv) if ok else 0.0
        if t == last_op:   # liquidation at PPA expiry: everything left goes to shareholders
            extra = trap + lu + dsra + mmra
            dv += extra; trap = 0.0; lu = 0.0
            dsra = 0.0
            rr['dsra_close'][t] = 0.0
            rr['final_dist'][t] = extra
        re_ = re_ + ni - dv
        rr['shl_int_paid'][t] = sip; rr['shl_prin'][t] = spr; rr['div'][t] = dv; rr['trap_close'][t] = trap
        rr['shl_close'][t] = shl if t >= t_cod else 0.0; rr['ni'][t] = ni; rr['re'][t] = re_; rr['book_dep'][t] = book_dep
        rr['int_exp'][t] = int_exp; rr['dt'][t] = dtv; rr['dt_exp'][t] = dt_exp
        rr['tax_exp'][t] = tax + dt_exp; rr['book_nbv'][t] = book_nbv; rr['tax_nbv'][t] = tax_nbv
        rr['equity_dist'][t] = sip + spr + dv
        rr['sc_bal'][t] = sc_bal
        # closing balances
        if t > t_cod:
            B[:, t] = Bo[:, t] - P[:, t] - LDp[:, t] - RF[:, t] - SW[:, t]
            if t == tR: B[5, t] = bond_F
    # store
    for k, nm in enumerate(names):
        S['bal_open_' + nm] = Bo[k]; S['bal_close_' + nm] = B[k]; S['principal_' + nm] = P[k]
        S['interest_' + nm] = I[k]; S['ld_prepay_' + nm] = LDp[k]; S['refi_prepay_' + nm] = RF[k]
        S['sweep_' + nm] = SW[k]; S['sched_' + nm] = SCH[k]; S['deferred_' + nm] = DFc[k]
        S['deferred_new_' + nm] = DFn[k]; S['deferred_repay_' + nm] = DFr[k]
    S.update(rr)
    S['flag_ds'] = flag_ds; S['prof'] = prof; S['N_s'] = N_s * swap_share
    S['debt_close'] = B.sum(0); S['debt_open'] = Bo.sum(0)
    R['S'] = S; R['last_op'] = last_op; R['t_cod'] = t_cod; R['t1'] = t1; R['fe'] = fe
    R['bond_F'] = bond_F; R['p'] = p
    ratios(R)
    returns(R)
    financials(R)
    return R


