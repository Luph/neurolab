def build_macro(p):
    us, kc = CPI[p['macro']]
    base_s = {'FC': FC_FWD, 'ACT': ACT_BASE, 'CODRF': RF_BASE}[p['macro']]
    base_s = np.array(base_s) + p['rate_shift'] * (np.arange(NS) >= SHOCK_T0)
    # FX semiannual average
    fx = np.zeros(NS)
    for t in range(NS):
        if p['macro'] == 'FC':
            fx[t] = FX_FC0 * p.get('fx_d', FX_D) ** ((t + 0.5) / 2)
        elif p['macro'] == 'ACT':
            fx[t] = FX_ACT_GIVEN[t] if t < 17 else fx[t - 1] * ((1 + kc[S_YEAR[t]] / 100) / (1 + us[S_YEAR[t]] / 100)) ** 0.5
        else:
            fx[t] = FX_ACT_GIVEN[t] if t <= 6 else fx[t - 1] * FX_D ** 0.5
    if p['deval'] > 0:
        fx = fx * np.where(np.arange(NS) >= SHOCK_T0, 1 / (1 - p['deval']), 1.0)
    fx_m = np.array([FX_FC0 * p.get('fx_d', FX_D) ** ((m + 0.5) / 12) if p['macro'] == 'FC' else fx[M_PER[m]]
                     for m in range(NM)])
    base_m = np.array([base_s[M_PER[m]] for m in range(NM)])
    if p['rate_shift']: base_m = np.array([({'FC': FC_FWD, 'ACT': ACT_BASE, 'CODRF': RF_BASE}[p['macro']])[M_PER[m]] for m in range(NM)])
    pol = np.array([13.5 if p['macro'] == 'FC' else POLICY_ACT.get(M_START[m].year, 15.5)
                    for m in range(NM)])

    # price indices: monthly geometric spread, 100 at Nov 2016
    def idx(g, y, mo):  # index at end of month 'mo' of year y
        v = 100 * (1 + g[2016] / 100) ** (1 / 12)
        for yy in range(2017, y):
            v *= 1 + g[yy] / 100
        return v * (1 + g[y] / 100) ** (mo / 12)
    out = {}
    for nm, g in (('us', us), ('kc', kc)):
        cost = np.zeros(NS)   # index at Mar (H1) / Sep (H2) of the period year
        tar = np.zeros(NS)    # index 3 months before reset: Sep prior year (H1) / Mar (H2)
        for t in range(NS):
            y = S_YEAR[t]
            if t == 0:
                cost[t] = idx(g, 2018, 9)
                tar[t] = idx(g, 2018, 3)
            else:
                f = ((1 + g[y - 1] / 100) ** 0.25 * (1 + g[y] / 100) ** 0.25) if S_HALF[t] == 1 \
                    else (1 + g[y] / 100) ** 0.5
                cost[t] = cost[t - 1] * f
                tar[t] = cost[t - 1]
            if 'E3' in ERRS:
                tar[t] = cost[t] * (1 + g[y] / 100) ** 0.25
        base18 = idx(g, 2018, 6)
        out[nm + '_cost'] = cost; out[nm + '_tar'] = tar; out[nm + '_base18'] = base18
        out[nm + '_cf'] = cost / base18
    out.update(base_s=base_s, base_m=base_m, fx=fx, fx_m=fx_m, pol=pol)
    return out

