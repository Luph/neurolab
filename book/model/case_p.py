def ratios(R):
    S = R['S']; NSs = NS
    debt_cost = S['senior_costs']
    rate = np.divide(debt_cost, S['debt_open'], out=np.zeros(NS), where=S['debt_open'] > 1e-9)
    S['allin_rate'] = rate
    # LLCR: PV of CFADS to final maturity at the all-in rate (+ DSRA balance) / debt outstanding
    fm = max([t for t in range(NS) if S['debt_open'][t] > 1e-9], default=0)
    pv = np.zeros(NS + 1); pvp = np.zeros(NS + 1)
    for t in range(NS - 1, -1, -1):
        r_ = rate[t] if rate[t] > 0 else rate[fm]
        pv[t] = (S['cfads'][t] + pv[t + 1]) / (1 + r_) if t <= fm else 0.0
        pvp[t] = (S['cfads'][t] + pvp[t + 1]) / (1 + r_) if t <= R['last_op'] else 0.0
    llcr = np.divide(pv[:NS], S['debt_open'], out=np.zeros(NS), where=S['debt_open'] > 1e-9)
    llcr_d = np.divide(pv[:NS] + S['dsra_open'], S['debt_open'], out=np.zeros(NS), where=S['debt_open'] > 1e-9)
    plcr = np.divide(pvp[:NS], S['debt_open'], out=np.zeros(NS), where=S['debt_open'] > 1e-9)
    S['pv_cfads_loan'] = pv[:NS]; S['llcr'] = llcr; S['llcr_dsra'] = llcr_d; S['plcr'] = plcr
    S['final_maturity_t'] = fm

