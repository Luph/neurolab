def breakeven(fn, lo, hi, target=1.0, it=60):
    flo = fn(lo) - target
    for _ in range(it):
        mid = (lo + hi) / 2; fm = fn(mid) - target
        if (fm > 0) == (flo > 0): lo, flo = mid, fm
        else: hi = mid
    return (lo + hi) / 2

