#!/usr/bin/env python3
"""
Case P reference model: Belanou Combined Cycle Power Project (Republic of Kessara).

Python mirror and computational source of truth for the Case P companion workbook
(Case_P_Model.xlsx, generated by build_excel_p.py).  Pure Python + numpy.

Reads  : model/inputs_case_p.json
Writes : model/outputs_case_p.json   (every period series and scalar, keyed by name)
         model/case_p_report.md       (human-readable summary tables)

Structure (mirrors the workbook sheets)
  Time         monthly construction timeline (Aug 2018 - Dec 2022, 53 months) and
               semiannual operating timeline (2018H2 - 2046H2, 57 periods)
  Construction monthly uses of funds (budget, actual overrun items, VAT)
  Funding      monthly sources: pro rata 75:25 debt/equity (FC-type scenarios) with a
               closed-form ("affine") gross-up of IDC/fees/premium/DSRA, or the actual
               funding cascade (committed facilities, LDs, DSU, standby + contingent equity)
  Operations   semiannual revenue (capacity, VOM, fuel pass-through), opex, working capital
  Tax          holiday, deferred depreciation, thin cap, minimum turnover tax
  Debt         tranches (ECA, A-loan, B-loan, commercial, standby, 2025 bond), swap
  Waterfall    CFADS, debt service, DSRA, lock-up, sweeps, distributions, dividend trap
  Financials   income statement, balance sheet, cash flow
  Ratios       DSCR (period and 12-month historic), LLCR, PLCR
  Returns      equity and project IRR (XIRR on dated flows)

Circularities and how they are resolved
  1. Construction: IDC, commitment fees, upfront fees, ECA premium and DSRA all depend on the
     facility size, which is 75% of the total funding requirement (T).  Python iterates
     T_{n+1} = U + F(0.75 T_n) to a tolerance of USD 1,000 (0.001 USD m).  The workbook solves
     the same fixed point in closed form: every month's balance is carried as
     alpha_m + beta_m * T, so T = alpha_end / (g - beta_end).  Both are reported.
  2. Sculpting: sculpted debt service depends on CFADS, CFADS depends on tax, and tax depends
     on interest (and on the shareholder-loan path).  Python iterates the whole model:
     profile -> model -> CFADS -> re-sculpted profile, to a tolerance of USD 1,000 on every
     installment.  After financial close the repayment profile is a contractual schedule
     (percentages of the loan), so the workbook carries the converged profile on the Inputs
     sheet and shows the live sculpting calculation with a check row (live minus contract).
     The same applies to the COD re-sculpting (2021) and the 2025 bond profile.
"""
