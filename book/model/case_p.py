def sculpt_rates(R, w, D, prof):
    """Per-period all-in rate on the scheduled balance for sculpting: weights w by tranche
    (ECA, A, B, COM, SB), swap notional relative to the scheduled balance."""
    mac_ = R['mac']; S = R['S']; p = R['p']; N_s = R['N_s']
    r = np.zeros(NS)
    for t in range(NS):
        base = mac_['base_s'][t]; dcf = S_DAYS[t] / 360
        mg = np.array([MARGIN[0], MARGIN[1], MARGIN[2], com_margin(S_YEAR[t])])
        rk = (base + mg) / 100 * (0.5 if 'E4' in ERRS else dcf) * GU
        rk[3] += PRI * S_DAYS[t] / 365
        rsb = sb_rate(mac_, t)
        rem = prof[t:].sum()
        bs = D * rem
        sw = (N_s[t] / bs) * (SWAP_FIX / 100 * 0.5 - base / 100 * dcf) * (-1 if 'E10' in ERRS else 1) if bs > 1e-9 else 0.0
        r[t] = (w[:4] * rk).sum() + w[4] * rsb + sw
    return r

def sculpt(R, D, t_first, t_last, w):
    """Constant-DSCR sculpting: DS_t = CFADS_t / DSCR*, DSCR* = PV(CFADS)/D."""
    S = R['S']; prof = R['prof']
    r = sculpt_rates(R, w, D, prof)
    cf = S['cfads'] + (S['tax'] if 'E8' in ERRS else 0)
    pv = 0.0
    for t in range(t_last, t_first - 1, -1):
        pv = (cf[t] + pv) / (1 + r[t])
    dscr = pv / D
    bal = D; newp = np.zeros(NS); ds = np.zeros(NS)
    for t in range(t_first, t_last + 1):
        ds[t] = cf[t] / dscr
        prin = ds[t] - bal * r[t]
        newp[t] = prin / D; bal -= prin
    return newp, dscr, pv, r, ds

def size_fc(p, gearing=0.75, dscr_target=1.35, down_target=1.20, verbose=False, max_it=200, only_gearing=False):
    """FC sizing: iterate (profile, notional, debt) -> model -> CFADS -> re-sculpt to convergence.
    Debt = min(gearing cap x T, PV(CFADS)/DSCR target, downside-constrained amount)."""
    _, t1 = first_ds_period(p); tl = tix('2034H1')
    prof = np.zeros(NS); prof[t1:tl + 1] = 1.0 / (tl - t1 + 1)
    N_m = np.zeros(NM); N_s = np.zeros(NS)
    D_fixed = None; hist = []
    pd = dict(p); pd.update(SCENARIOS[3]); pd['name'] = 'FC downside'; pd['fund_mode'] = 'size'
    for it in range(1, max_it + 1):
        p['fund_mode'] = 'size'
        R = run(p, prof, N_m, N_s, None, D_fixed, gearing)
        D = R['f']['D']; T = R['f']['T']
        newp, dscr, pv, r, ds = sculpt(R, D, t1, tl, SHARE_W())
        cap_ = pv / dscr_target
        if down_target:
            Rd = run(pd, prof, N_m, N_s, None, D, gearing)
            md = min(Rd['S']['dscr'][t] for t in range(t1, tl + 1))
        else:
            md = 9.99
        cap_down = D * md / down_target if down_target else 1e9
        fe = R['fe']; bal_m = sum(R['f']['bal_' + k] for k in TR)
        newNm = np.zeros(NM); newNm[1:fe + 1] = 0.8 * bal_m[:fe]
        newNs = np.zeros(NS)
        for t in range(t1, NS):
            newNs[t] = 0.8 * D * newp[t:].sum()
        cands = {'gearing': gearing * T, 'DSCR': cap_, 'downside': cap_down if down_target else 1e9}
        bind = 'gearing' if only_gearing else min(cands, key=cands.get)
        newD_fixed = None if bind == 'gearing' else cands[bind]
        diff = max(np.abs((newp - prof) * D).max(), np.abs(newNm - N_m).max(), np.abs(newNs - N_s).max(),
                   abs((newD_fixed or 0) - (D_fixed or 0)))
        hist.append(diff)
        prof, N_m, N_s, D_fixed = newp, newNm, newNs, newD_fixed
        if diff < TOL * 0.01 and it > 2:
            break
    R = run(p, prof, N_m, N_s, None, D_fixed, gearing)
    R['sizing_iterations'] = it; R['sizing_hist'] = hist
    newp, dscr, pv, r, ds = sculpt(R, R['f']['D'], t1, tl, SHARE_W())
    R['sculpt_dscr'] = dscr; R['sculpt_pv'] = pv; R['capacity'] = pv / dscr_target
    R['cands'] = cands; R['downside_min'] = md
    R['sculpt_check'] = np.abs((newp - prof) * R['f']['D']).max()
    R['binding'] = bind
    return R

def SHARE_W():
    return np.array([0.30, 0.22, 0.10, 0.38, 0.0])

def resculpt_cod(p):
    """Lenders' COD re-sculpting on the COD re-forecast case (scenario 14)."""
    _, t1 = first_ds_period(p); tl = tix('2034H1')
    prof = np.zeros(NS); prof[t1:tl + 1] = 1.0 / (tl - t1 + 1)
    for it in range(1, 200):
        R = run(p, prof)
        fe = R['fe']; f = R['f']
        bal = np.array([f['bal_' + k][fe] for k in TR] + [f['bal_SB'][fe]])
        D = bal.sum(); w = bal / D
        newp, dscr, pv, r, ds = sculpt(R, D, t1, tl, w)
        diff = np.abs((newp - prof) * D).max()
        prof = newp
        if diff < TOL * 0.01: break
    R = run(p, prof)
    R['sizing_iterations'] = it
    newp, dscr, pv, r, ds = sculpt(R, D, t1, tl, w)
    R['sculpt_dscr'] = dscr; R['sculpt_check'] = np.abs((newp - prof) * D).max(); R['sculpt_w'] = w
    return R

def bond_sculpt(R):
    """2025 bond: combined DS (ECA + A-loan + bond) sculpted to constant DSCR >= 1.35 to 2037H1."""
    S = R['S']; F = R['bond_F']; t0 = tix('2025H2'); tl = tix('2037H1')
    rb = 7.875 / 100 * 0.5 + 0.011 * 0.5 * 95.0 / F
    other = np.zeros(NS)
    for k in ['ECA', 'A']:
        other += S['interest_' + k] + S['principal_' + k]
    other += S['swap']
    pvc = sum(S['cfads'][t] / (1 + rb) ** (t - t0 + 1) for t in range(t0, tl + 1))
    pvo = sum(other[t] / (1 + rb) ** (t - t0 + 1) for t in range(t0, tl + 1))
    dscr = pvc / (F + pvo)
    bal = F; bp = np.zeros(NS)
    for t in range(t0, tl + 1):
        bds = S['cfads'][t] / dscr - other[t]
        prin = bds - bal * rb
        bp[t] = prin / F; bal -= prin
    return bp, dscr

def solve_actual(p, verbose=False):
    t0 = tix('2025H2'); tl = tix('2037H1')
    bp = np.zeros(NS); bp[t0:tl + 1] = 1.0 / (tl - t0 + 1)
    for it in range(1, 200):
        R = run(p, bond_prof=bp)
        nbp, dscr = bond_sculpt(R)
        diff = np.abs((nbp - bp) * R['bond_F']).max()
        bp = nbp
        if diff < TOL * 0.01: break
    R = run(p, bond_prof=bp)
    nbp, dscr = bond_sculpt(R)
    R['bond_iterations'] = it; R['bond_dscr'] = dscr
    R['bond_check'] = np.abs((nbp - bp) * R['bond_F']).max()
    return R, bp

def build_contract():
    """Run the three sizing problems in story order and fix the contract terms."""
    R1 = size_fc(scen(1))
    f = R1['f']
    CONTRACT.update(Dk=list(f['Dk']), D=f['D'], T=f['T'], E=f['T'] - f['D'],
                    prof_FC=list(R1['prof']), N_m=list(R1['N_m']), N_s=list(R1['N_s']))
    R14 = resculpt_cod(scen(14))
    CONTRACT['prof_COD'] = list(R14['prof'])
    CONTRACT['prof_BOND'] = [0.0] * NS
    R15, bp = solve_actual(scen(15))
    CONTRACT['prof_BOND'] = list(bp)
    return R1, R14, R15


