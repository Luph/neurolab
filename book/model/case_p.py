def first_ds_period(p):
    cod = cod_date(p)
    t_cod = [t for t in range(NS) if S_START[t] <= cod <= S_END[t]][0]
    return t_cod, t_cod + 1

def fund_end_month(p):
    t_cod, _ = first_ds_period(p)
    return max(m for m in range(NM) if M_PER[m] == t_cod)

def ds_rate_vector(p, mac_, t):
    """Per-tranche all-in loan rate for period t (fraction of balance per period)."""
    base = mac_['base_s'][t]; dcf = S_DAYS[t] / 360
    mg = MARGIN.copy(); mg[3] = com_margin(S_YEAR[t])
    r = (base + mg) / 100 * (0.5 if 'E4' in ERRS else dcf) * GU
    r[3] += PRI * S_DAYS[t] / 365
    return r

def dsra_coeffs(p, mac_, prof, N_s):
    """DSRA at COD = d1 . balances + d0 (next-period debt service on fully drawn balances)."""
    _, t1 = first_ds_period(p)
    r = ds_rate_vector(p, mac_, t1)
    d1 = prof[t1] / prof[t1:].sum() + r
    d0 = N_s[t1] * (SWAP_FIX / 100 * 0.5 - mac_['base_s'][t1] / 100 * S_DAYS[t1] / 360) * (-1 if 'E10' in ERRS else 1)
    return d1, d0

def month_rates(mac_, m):
    base = mac_['base_m'][m]; dcf = M_DAYS[m] / 360
    rho = (base + MARGIN) / 100 * ((1 / 12) if 'E4' in ERRS else dcf) * GU          # construction: commercial margin 4.10
    rho[3] += PRI * M_DAYS[m] / 365
    kap = CFEE / 100 * dcf
    return rho, kap

def funding_fc(p, mac_, u, prof, N_m, N_s, D_fixed=None, mode='size'):
    """FC-type funding, pro rata debt/equity.
    mode 'size'    : Python sizing loop; D = G*T (or D_fixed), g = D/T, T by fixed-point iteration
    mode 'contract': committed amounts D_c, E_c from the FC sizing; g = D_c/(D_c+E_c); one pass
    mode 'regross' : g = D_c/(D_c+E_c) and D = g*T (capex +10%, COD delay); T by iteration
    The workbook's closed-form (affine) gross-up is reproduced for cross-check."""
    fe = fund_end_month(p); nc = u['nc']
    d1, d0 = dsra_coeffs(p, mac_, prof, N_s)
    if mode == 'contract':
        Dc = CONTRACT['D']; gc = Dc / (Dc + CONTRACT['E'])
        if 'E7' in ERRS:
            ds_ = (d1 * SHARE * Dc).sum() + d0
            gc = (Dc - ds_) / (Dc + CONTRACT['E'] - ds_)
        r = _fund_fc_pass(p, mac_, u, Dc, gc, fe, nc, d1, d0, N_m)
        r['iterations'] = 1; r['T'] = r['uses'].sum()
        g_aff = G
    else:
        gfix = None if mode == 'size' else CONTRACT['D'] / (CONTRACT['D'] + CONTRACT['E'])
        T = u['base_total'].sum() * 1.15; it = 0
        while True:
            it += 1
            if mode == 'size' and 'E7' in ERRS:
                if it == 1: D, g = G * T, G
                elif D_fixed is None: D, g = Dn_, G
                else: g = g * D_fixed / Dn_; D = D_fixed
            elif mode == 'size':
                D = G * T if D_fixed is None else D_fixed; g = D / T
            else:
                g = gfix; D = g * T
            r = _fund_fc_pass(p, mac_, u, D, g, fe, nc, d1, d0, N_m)
            Tn = r['uses'].sum(); Dn_ = r['debt_draw'].sum()
            if abs(Tn - T) < 1e-9 and ('E7' not in ERRS or abs(Dn_ - D) < 1e-9):
                T = Tn; break
            T = Tn
            if it > 500: raise RuntimeError('funding did not converge')
        r['iterations'] = it; r['T'] = T
        g_aff = G if mode == 'size' else gfix
    # closed-form (affine) gross-up as built in the workbook: balance_m = alpha_m + beta_m * T
    a = b = 0.0; A = np.zeros(NM); B = np.zeros(NM); g = g_aff
    den = 1 - ECA_PREM * SHARE[0] * g
    for m in range(NM):
        if m > fe: A[m], B[m] = a, b; continue
        rho, kap = month_rates(mac_, m)
        rr = (SHARE * rho).sum(); kk = (SHARE * kap).sum()
        const = (u['base_total'][m] + u['vat_int'][m] + 0.255 / 12
                 + N_m[m] * (SWAP_FIX / 100 / 12 - mac_['base_m'][m] / 100 * M_DAYS[m] / 360)
                 + SB_COMMIT * SB_CFEE / 100 * M_DAYS[m] / 360)
        cod_m = (m == nc)
        const += d0 if cod_m else 0.0
        a_new = a + g / den * (const + rr * a - kk * a)
        b_new = b + g / den * (rr * b + kk * (g - b) + (g * (SHARE * UPF / 100).sum() if m == 0 else 0)
                               + (g * (SHARE * d1).sum() if cod_m else 0))
        a, b = a_new, b_new; A[m], B[m] = a, b
    r['alpha'] = A; r['beta'] = B; r['g_aff'] = g; r['T_closed_form'] = A[fe] / (g - B[fe])
    return r

def _fund_fc_pass(p, mac_, u, D, g, fe, nc, d1, d0, N_m):
    Dk = SHARE * D
    bal = np.zeros(4); out = {k: np.zeros(NM) for k in
        ['idc', 'swap', 'pri', 'cfee', 'upfront', 'agency', 'eca_prem', 'dsra', 'uses',
         'debt_draw', 'equity', 'equity_cash', 'shl_contrib', 'sc_contrib', 'shl_capint',
         'shl_bal', 'fin_costs', 'sb_cfee', 'loan_int']}
    for k in range(4):
        out['draw_' + TR[k]] = np.zeros(NM); out['bal_' + TR[k]] = np.zeros(NM)
        out['idc_' + TR[k]] = np.zeros(NM)
    shl = 0.0
    den = 1 - ECA_PREM * SHARE[0] * g
    for m in range(NM):
        if m > fe:
            for k in range(4): out['bal_' + TR[k]][m] = bal[k]
            out['shl_bal'][m] = shl; continue
        rho, kap = month_rates(mac_, m)
        idc_k = bal * (mac_['base_m'][m] + MARGIN) / 100 * ((1 / 12) if 'E4' in ERRS else M_DAYS[m] / 360) * GU
        pri = PRI * bal[3] * M_DAYS[m] / 365
        swap = N_m[m] * (SWAP_FIX / 100 / 12 - mac_['base_m'][m] / 100 * M_DAYS[m] / 360) * (-1 if 'E10' in ERRS else 1)
        cfee = ((Dk - bal) * kap).sum()
        sbf = SB_COMMIT * SB_CFEE / 100 * M_DAYS[m] / 360
        upf = (Dk * UPF / 100).sum() if m == 0 else 0.0
        dsra = (d1 * Dk).sum() + d0 if m == nc else 0.0
        X = (u['base_total'][m] + u['vat_int'][m] + idc_k.sum() + pri + swap + cfee + sbf
             + upf + 0.255 / 12 + dsra)
        if 'E7' in ERRS:   # seeded error: DSRA funded 100% by senior debt
            draw = (g * (X - dsra) + dsra) / den
            uses = X + ECA_PREM * SHARE[0] * draw
        else:
            uses = X / den
            draw = g * uses
        prem = ECA_PREM * SHARE[0] * draw
        for k in range(4):
            out['draw_' + TR[k]][m] = SHARE[k] * draw
            out['idc_' + TR[k]][m] = idc_k[k]
        bal = bal + SHARE * draw
        eq = uses - draw
        shl_int = shl * SHL_RATE / 100 * M_DAYS[m] / 365 if m < nc else 0.0
        shl += shl_int + p['shl_share'] * eq
        out['idc'][m] = idc_k.sum() + pri + swap; out['loan_int'][m] = idc_k.sum()
        out['swap'][m] = swap; out['pri'][m] = pri; out['cfee'][m] = cfee; out['sb_cfee'][m] = sbf
        out['upfront'][m] = upf; out['agency'][m] = 0.255 / 12; out['eca_prem'][m] = prem
        out['dsra'][m] = dsra; out['uses'][m] = uses; out['debt_draw'][m] = draw
        out['equity'][m] = eq; out['equity_cash'][m] = eq - (LNTP if m == 0 else 0)
        out['shl_contrib'][m] = p['shl_share'] * eq; out['sc_contrib'][m] = (1 - p['shl_share']) * eq
        out['shl_capint'][m] = shl_int; out['shl_bal'][m] = shl
        out['fin_costs'][m] = (idc_k.sum() + pri + swap + cfee + sbf + upf + 0.255 / 12 + prem
                               + u['vat_int'][m])
        for k in range(4): out['bal_' + TR[k]][m] = bal[k]
    out['D'] = D; out['Dk'] = Dk; out['g'] = g
    out['sb_draw'] = np.zeros(NM); out['ce_draw'] = np.zeros(NM); out['bal_SB'] = np.zeros(NM)
    out['ld_used'] = np.zeros(NM); out['ld_pool'] = np.zeros(NM); out['base_fund'] = out['uses'].copy()
    out['ld_leftover'] = 0.0
    return out

def funding_act(p, mac_, u, prof, N_m, N_s):
    """Actual funding cascade: committed FC facilities pro rata, then LDs/DSU, then standby
    and contingent equity 75:25."""
    fe = fund_end_month(p); nc = u['nc']
    Dk = np.array(CONTRACT['Dk']); E_fc = CONTRACT['E']; g = Dk.sum() / (Dk.sum() + E_fc)
    d1, d0 = dsra_coeffs(p, mac_, prof, N_s)
    _, t1 = first_ds_period(p)
    rsb_t1 = sb_rate(mac_, t1)
    bal = np.zeros(4); sb = 0.0; shl = 0.0; pool = 0.0; eq_cum = 0.0
    out = {k: np.zeros(NM) for k in
        ['idc', 'swap', 'pri', 'cfee', 'upfront', 'agency', 'eca_prem', 'dsra', 'uses',
         'debt_draw', 'equity', 'equity_cash', 'shl_contrib', 'sc_contrib', 'shl_capint',
         'shl_bal', 'fin_costs', 'sb_cfee', 'sb_draw', 'ce_draw', 'bal_SB', 'ld_used',
         'ld_pool', 'base_fund', 'ld_received', 'loan_int', 'sb_int']}
    for k in range(4):
        out['draw_' + TR[k]] = np.zeros(NM); out['bal_' + TR[k]] = np.zeros(NM)
        out['idc_' + TR[k]] = np.zeros(NM)
    for m in range(NM):
        if m > fe:
            for k in range(4): out['bal_' + TR[k]][m] = bal[k]
            out['bal_SB'][m] = sb; out['shl_bal'][m] = shl; out['ld_pool'][m] = pool; continue
        base = mac_['base_m'][m]; dcf = M_DAYS[m] / 360
        idc_k = bal * (base + MARGIN) / 100 * dcf * GU
        sbi = sb * sb_rate_m(base) * dcf
        pri = PRI * bal[3] * M_DAYS[m] / 365
        swap = N_m[m] * (SWAP_FIX / 100 / 12 - base / 100 * dcf)
        cfee = ((Dk - bal) * CFEE / 100 * dcf).sum()
        sbf = (SB_COMMIT - sb) * SB_CFEE / 100 * dcf
        upf = (Dk * UPF / 100).sum() if m == 0 else 0.0
        dsra = ((d1 * bal).sum() + sb * (prof[t1] / prof[t1:].sum() + rsb_t1) + d0) if m == nc else 0.0
        X = (u['base_total'][m] + u['vat_int'][m] + idc_k.sum() + sbi + pri + swap + cfee + sbf
             + upf + 0.255 / 12 + dsra)
        HD = Dk.sum() - bal.sum()
        bdebt = min(g * X / (1 - ECA_PREM * SHARE[0] * g), HD)
        prem = ECA_PREM * SHARE[0] * bdebt
        uses = X + prem
        bfund = bdebt / g
        R1 = uses - bfund
        rec = (OVR['epc_delay_lds_usd_m'] + OVR['dsu_proceeds_usd_m']) if m == RECEIPT_M else 0.0
        avail = pool + rec
        ldu = min(R1, avail); pool = avail - ldu
        R2 = R1 - ldu
        sbd, ce = 0.75 * R2, 0.25 * R2
        for k in range(4):
            out['draw_' + TR[k]][m] = SHARE[k] * bdebt; out['idc_' + TR[k]][m] = idc_k[k]
        bal = bal + SHARE * bdebt; sb += sbd
        eq = bfund - bdebt + ce
        shl_int = shl * SHL_RATE / 100 * M_DAYS[m] / 365 if m < nc else 0.0
        shl += shl_int + p['shl_share'] * eq
        out['idc'][m] = idc_k.sum() + sbi + pri + swap; out['loan_int'][m] = idc_k.sum()
        out['sb_int'][m] = sbi
        out['swap'][m] = swap; out['pri'][m] = pri; out['cfee'][m] = cfee; out['sb_cfee'][m] = sbf
        out['upfront'][m] = upf; out['agency'][m] = 0.255 / 12; out['eca_prem'][m] = prem
        out['dsra'][m] = dsra; out['uses'][m] = uses; out['debt_draw'][m] = bdebt + sbd
        out['equity'][m] = eq; out['equity_cash'][m] = eq - (LNTP if m == 0 else 0)
        out['shl_contrib'][m] = p['shl_share'] * eq; out['sc_contrib'][m] = (1 - p['shl_share']) * eq
        out['shl_capint'][m] = shl_int; out['shl_bal'][m] = shl
        out['sb_draw'][m] = sbd; out['ce_draw'][m] = ce; out['bal_SB'][m] = sb
        out['ld_used'][m] = ldu; out['ld_pool'][m] = pool; out['base_fund'][m] = bfund
        out['ld_received'][m] = rec
        out['fin_costs'][m] = (idc_k.sum() + sbi + pri + swap + cfee + sbf + upf + 0.255 / 12
                               + prem + u['vat_int'][m])
        for k in range(4): out['bal_' + TR[k]][m] = bal[k]
    out['D'] = Dk.sum(); out['Dk'] = Dk; out['g'] = g; out['T'] = out['uses'].sum()
    out['ld_leftover'] = pool; out['iterations'] = 1
    return out

def sb_rate_m(base):
    """Standby all-in rate (% pa, before day count): 60% commercial (margin 4.10+0.25, grossed
    up for 10% WHT), 40% ABDB (3.65+0.25)."""
    return (0.6 * (base + 4.10 + 0.25) / 0.9 + 0.4 * (base + 3.65 + 0.25)) / 100

def sb_rate(mac_, t):
    base = mac_['base_s'][t]; cm = com_margin(S_YEAR[t])
    return (0.6 * (base + cm + 0.25) / 0.9 + 0.4 * (base + 3.65 + 0.25)) / 100 * S_DAYS[t] / 360

